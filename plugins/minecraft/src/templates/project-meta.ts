function projectReadme(context: TemplateContext): string {
  const platforms = context.platforms.map((id) => `\`${id}\``).join(" + ");
  const modules = context.modules.length > 1 ? context.modules.join(", ") : "single module";

  return [
    `# ${context.name}`,
    "",
    `Minecraft ${context.kind} project generated by [Devix](https://github.com/hauchdev/Devix).`,
    "",
    "## Platforms",
    "",
    `- **Minecraft**: ${context.versions[0]?.minecraft ?? "unknown"}`,
    `- **Java**: ${String(context.versions[0]?.javaVersion ?? 21)}`,
    `- **Platforms**: ${platforms}`,
    `- **Modules**: ${modules}`,
    "",
    "## Build",
    "",
    "This project uses Gradle. If the wrapper jar is present:",
    "",
    "```bash",
    "./gradlew build",
    "```",
    "",
    "On Windows:",
    "",
    "```powershell",
    ".\\gradlew.bat build",
    "```",
    "",
    "> The wrapper jar (`gradle/wrapper/gradle-wrapper.jar`) is not generated by Devix. If it is missing and you have Gradle installed, run `gradle wrapper` once to download it, or copy the jar from any recent Gradle project.",
    "",
    "## Run",
    "",
    "Use Devix to print the launch command without executing it:",
    "",
    "```bash",
    `devix minecraft run --cwd <path>`,
    "```",
    "",
    "## Project structure",
    "",
    "- `src/main/java/` — Java source code.",
    "- `src/main/resources/` — Mod/plugin metadata and assets.",
    context.multimodule ? "- `*/` — additional Gradle subprojects." : "",
    "",
    "## License",
    "",
    "MIT — see [LICENSE](./LICENSE).",
    "",
  ]
    .filter((line) => line !== undefined)
    .join("\n");
}

function ciWorkflow(): string {
  return [
    "name: Build",
    "",
    "on:",
    "  push:",
    "    branches:",
    "      - main",
    "  pull_request:",
    "    branches:",
    "      - main",
    "",
    "jobs:",
    "  build:",
    "    runs-on: ${{ matrix.os }}",
    "    strategy:",
    "      matrix:",
    "        os: [ubuntu-latest, windows-latest]",
    "        java: [21]",
    "    steps:",
    "      - name: Checkout",
    "        uses: actions/checkout@v4",
    "",
    "      - name: Set up JDK ${{ matrix.java }}",
    "        uses: actions/setup-java@v4",
    "        with:",
    "          distribution: temurin",
    "          java-version: ${{ matrix.java }}",
    "",
    "      - name: Validate Gradle wrapper",
    "        uses: gradle/actions/wrapper-validation@v3",
    "",
    "      - name: Build with Gradle",
    "        run: ./gradlew build",
    "        shell: bash",
    "",
  ].join("\n");
}

/**
 * Project-level files every scaffold should include: Gradle wrapper
 * scripts/properties, .gitignore, .editorconfig, LICENSE, README and a
 * starter CI workflow. The wrapper jar itself is intentionally excluded
 * from generation; users complete it with `gradle wrapper` or an existing
 * Gradle installation.
 */
export function renderProjectMeta(context: TemplateContext): TemplateFile[] {
  return [
    { path: "gradle/wrapper/gradle-wrapper.properties", contents: gradleWrapperProperties() },
    { path: "gradlew", contents: gradlewShell() },
    { path: "gradlew.bat", contents: gradlewBat() },
    { path: ".gitignore", contents: gitignore(context) },
    { path: ".editorconfig", contents: editorConfig() },
    { path: "LICENSE", contents: license() },
    { path: "README.md", contents: projectReadme(context) },
    { path: ".github/workflows/build.yml", contents: ciWorkflow() },
  ];
}
